def export_figure(fig: Figure, result: dict, spec: PlotSpec, opts: dict, mapping: dict, source: str,
                  folder: Path, formats=("png", "svg", "pdf"), dpi: int = 300, sheet=None,
                  extras_mapping: dict | None = None, synthetic: bool = False) -> dict:
    stamp = time.strftime("%Y%m%d-%H%M%S")
    out_dir = Path(folder) / f"{stamp}_{_slug(spec.id + '_' + spec.title)}"
    out_dir.mkdir(parents=True, exist_ok=True)
    base = out_dir / "figure"
    files = []
    with matplotlib.rc_context(RC):
        for fmt in formats:
            p = base.with_suffix("." + fmt)
            fig.savefig(p, dpi=dpi, bbox_inches="tight")
            files.append(str(p))
    script = out_dir / "make_figure.py"
    script.write_text(build_script(spec, opts, mapping, source, sheet, extras_mapping), encoding="utf-8")
    config = {"plot": spec.id, "title": spec.title, "options": opts, "mapping": mapping,
              "extras_mapping": extras_mapping or {}, "data_file": source, "dpi": dpi, "formats": list(formats),
              "statistics": result.get("stats", []), "notes": result.get("notes", []),
              "data_marked_synthetic": synthetic, "created": stamp}
    (out_dir / "config.json").write_text(json.dumps(config, indent=2, ensure_ascii=False), encoding="utf-8")
    (out_dir / "README.txt").write_text(
        f"{spec.title}\n\nQuestion: {spec.question}\nInterpretation: {spec.interpretation}\n"
        f"Alternative explanations: {spec.alternatives}\nConfounders: {spec.confounders}\n\nStatistics:\n  "
        + "\n  ".join(result.get("stats", [])) + "\n\nNotes:\n  " + "\n  ".join(result.get("notes", []))
        + ("\n\nWARNING: the input data file is marked SYNTHETIC." if synthetic else ""), encoding="utf-8")
    return {"folder": str(out_dir), "files": files, "script": str(script)}
