"""Generate the SYNTHETIC example datasets shipped with IsoResearch AI.

!!! These numbers are artificial. They are NOT observations from Port Blair or
anywhere else and must never be used as data in a publication. They only
exist so you can try the Data Analysis and Plot Advisor workspaces.

Run:  python examples/make_synthetic_data.py
"""
from pathlib import Path

import numpy as np
import pandas as pd

HERE = Path(__file__).resolve().parent
rng = np.random.default_rng(42)


def rainfall_csv() -> Path:
    days = pd.date_range("2024-05-15", "2024-11-30", freq="D")
    rain_days = np.sort(rng.choice(days, size=110, replace=False))
    t = pd.DatetimeIndex(rain_days) + pd.to_timedelta(rng.integers(0, 24, len(rain_days)), unit="h")
    precip = np.round(rng.gamma(1.1, 14.0, len(t)), 1)
    intensity = np.round(precip / rng.uniform(1, 8, len(t)), 2)
    doy = t.dayofyear.values
    season = -2.0 * np.sin((doy - 140) / 200 * np.pi)
    d18o = np.round(-1.0 + season - 0.06 * precip + rng.normal(0, 1.1, len(t)), 2)
    dex = np.round(10 + 3 * np.cos((doy - 150) / 180 * np.pi) + rng.normal(0, 2.2, len(t)), 2)
    d2h = np.round(8 * d18o + dex, 2)
    temp = np.round(27.5 - 0.03 * precip + rng.normal(0, 0.8, len(t)), 1)
    rh = np.round(np.clip(80 + 0.15 * precip + rng.normal(0, 4, len(t)), 50, 100), 1)
    q = np.round(18.5 + 0.02 * precip + rng.normal(0, 0.8, len(t)), 2)
    traj = np.round(np.clip(5 + 0.4 * precip + rng.normal(0, 6, len(t)), 0, None), 1)
    d18o_sim = np.round(d18o * 0.8 - 0.6 + rng.normal(0, 0.9, len(t)), 2)
    d2h_sim = np.round(d2h * 0.82 - 3 + rng.normal(0, 7, len(t)), 2)
    event = np.where(precip > 20, (np.arange(len(t)) // 3) + 1, np.nan)
    df = pd.DataFrame({"date_time": t, "event_id": event, "rain_mm": precip, "intensity_mm_h": intensity,
                       "T_air_C": temp, "RH_pct": rh, "q_g_kg": q, "d18O_permil": d18o, "d2H_permil": d2h,
                       "d18O_IsoRSM": d18o_sim, "d2H_IsoRSM": d2h_sim, "traj_rain_upstream_mm": traj})
    # a couple of intra-event sequences
    rows = []
    for e, start in enumerate(pd.to_datetime(["2024-07-10 02:00", "2024-08-21 14:00"]), start=101):
        base = rng.normal(-3, 0.5)
        for k in range(6):
            rows.append({"date_time": start + pd.Timedelta(minutes=30 * k), "event_id": e,
                         "rain_mm": round(rng.uniform(2, 9), 1), "d18O_permil": round(base - 0.7 * k + rng.normal(0, 0.3), 2)})
    df = pd.concat([df, pd.DataFrame(rows)], ignore_index=True)
    out = HERE / "synthetic_rainfall_isotopes.csv"
    with open(out, "w", encoding="utf-8", newline="") as fh:
        fh.write("# SYNTHETIC DATA — generated by examples/make_synthetic_data.py; NOT real observations.\n")
        fh.write("# Columns: rain_mm [mm], intensity_mm_h [mm/h], T_air_C [degC], RH_pct [%], q_g_kg [g/kg], "
                 "isotopes in permil VSMOW; *_IsoRSM are synthetic 'model' values.\n")
        df.to_csv(fh, index=False)
    return out


def profile_nc() -> Path:
    import xarray as xr

    p = np.array([1000, 925, 850, 700, 600, 500, 400, 300], float)
    n = len(p)
    xa = np.linspace(-80, -260, n)
    xm = xa + rng.normal(0, 15, n) + np.linspace(10, -20, n)
    A = np.zeros((n, n))
    for i in range(n):
        A[i] = np.exp(-0.5 * ((np.arange(n) - min(i, 4)) / 1.3) ** 2)
        A[i] /= A[i].sum() * 1.4
    retr = xa + A @ (xm - xa) + rng.normal(0, 5, n)
    times = pd.date_range("2024-07-01", periods=12, freq="5D")
    ds = xr.Dataset(
        {"avg_kernel": (("lev", "lev2"), A), "apriori": ("lev", xa), "model_profile": ("lev", xm),
         "retrieval": ("lev", retr),
         "dD_insitu": ("time", np.round(rng.normal(-75, 6, len(times)), 1)),
         "dD_satellite": ("time", np.round(rng.normal(-95, 9, len(times)), 1)),
         "dD_model": ("time", np.round(rng.normal(-82, 5, len(times)), 1))},
        coords={"lev": ("lev", p, {"units": "hPa"}), "lev2": ("lev2", p), "time": times},
        attrs={"title": "SYNTHETIC averaging-kernel example", "comment": "SYNTHETIC — not real retrievals"})
    for v, u in (("apriori", "permil"), ("model_profile", "permil"), ("retrieval", "permil"),
                 ("dD_insitu", "permil"), ("dD_satellite", "permil"), ("dD_model", "permil")):
        ds[v].attrs["units"] = u
    out = HERE / "synthetic_satellite_profiles.nc"
    ds.to_netcdf(out)
    return out


if __name__ == "__main__":
    print(rainfall_csv())
    print(profile_nc())
